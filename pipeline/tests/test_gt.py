def test_load_overrides_roundtrip_and_duplicate(tmp_path):
    p = tmp_path / "o.csv"
    with open(p, "w", newline="", encoding="utf-8") as f:
        w = csv.writer(f)
        w.writerow(["snapshot", "issue_number", "model", "field", "value", "reason"])
        w.writerow(["v8", 5, "gpt-5", "fixed", "yes", "porque"])
    assert gt.load_overrides(p) == {("v8", 5, "gpt-5", "fixed"): ("yes", "porque")}
    with open(p, "a", newline="", encoding="utf-8") as f:
        csv.writer(f).writerow(["v8", 5, "gpt-5", "fixed", "no", "de novo"])
    with pytest.raises(ValueError, match="duplicado"):
        gt.load_overrides(p)
    assert gt.load_overrides(tmp_path / "nao_existe.csv") == {}


def test_assign_ids_suffix_and_status():
    df = pd.DataFrame({"snapshot": ["v8"] * 4, "file_number": [1, 1, 1, 2], "line": [1, 1, 7, 1],
                       "issue_number": [1, 2, 3, 4], "is_real_label": ["real", "real", "not_real", "real"]})
    out = gt.assign_ids(df)
    assert out["issue_id"].tolist() == ["v8:1/1a", "v8:1/1b", "v8:1/7", "v8:2/1"]
    st = gt.classify_status(out, canonical=("v8:1/1a", "v8:1/1b"))
    assert st["status"].tolist() == ["real", "real", "known_fp", "divergent"]   # real fora da lista canonica = divergente
    with pytest.raises(ValueError, match="ausentes"):
        gt.classify_status(out, canonical=("v8:1/1a", "v8:1/1b", "v8:9/9"))



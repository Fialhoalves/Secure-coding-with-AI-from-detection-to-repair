# --------------------------------------------------------------------------- planilha .ods sintetica
def _ods(path, sheet_name, data_rows, second_model="ChatGPT-5"):
    """Cria um .ods com a linha em branco + 2 linhas de cabecalho do layout dos autores."""
    doc = OpenDocumentSpreadsheet()
    table = Table(name=sheet_name)
    group = ["File number", "GitHub Link", "Programming language", "Is original code generated by ChatGPT?",
             "LLMs name", "Issue Number", "Severity", "Line", "CWE type", "Scanners ",
             "Is this detect actual security problem? (Vlad)",
             "ChatGPT-4.1", None, None, second_model, None, None, "Claude Opus 4.1", None, None, "Comment"]
    sub = group[:11] + ["Was issue detected by LLM?", "Was issue fixed?", "CWE identified in file"] + \
        ["Was issue detected by?", "Was issue fixed?", "CWE identified in file"] * 2 + ["Comment"]
    sub[11 + 3] = "Was issue detected by?"
    all_rows = [[None] * 21, group, sub] + data_rows
    for r in all_rows:
        tr = TableRow()
        for v in r:
            tc = TableCell(valuetype="string") if v is not None else TableCell()
            if v is not None:
                tc.addElement(P(text=str(v)))
            tr.addElement(tc)
        table.addElement(tr)
    doc.spreadsheet.addElement(table)
    doc.save(str(path))


def _row(file_number, issue, line, scanners, verdict, lang="C", origin="Yes", det=("Yes", None, None, None, None, None, None, None, None)):
    cells = [file_number, "Link" if file_number else None, lang if file_number else None,
             origin if file_number else None, None, issue, "note", line, "CWE-120", scanners, verdict]
    return cells + list(det) + [None]



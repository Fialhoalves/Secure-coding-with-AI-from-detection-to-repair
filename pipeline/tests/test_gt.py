INFO = '''Model name: ---
File name: c:\\x\\Conversation_001\\Code_002.c
Scanners: ['flawfinder', 'snyk']

Detect info from scanners:
[
    {"line": 1, "severity": "note", "text": "open (CWE-362)", "type": "FF1040", "source_code": "int fd = open(p);", "scanner": "flawfinder"},
    {"line": 1, "severity": "note", "text": "leak", "type": "cpp/CMissingClose", "source_code": "int fd = open(p);", "scanner": "snyk"},
    {"line": 9, "severity": "warning", "text": "strcpy", "type": "cpp/Unsafe", "source_code": "strcpy(a, b);", "scanner": "snyk"}
]
'''


def test_parse_info_and_detection_lookup():
    info = parse_info(INFO)
    assert info["scanners"] == ["flawfinder", "snyk"] and len(info["detections"]) == 3
    assert info["scanned_file"].endswith("Code_002.c")
    dets, mode = detections_for(info["detections"], 1, ["snyk"])
    assert mode == "strict" and [d["scanner"] for d in dets] == ["snyk"]
    dets, mode = detections_for(info["detections"], 9, ["flawfinder"])       # linha certa, scanner trocado
    assert mode == "line_only" and dets[0]["scanner"] == "snyk"
    dets, mode = detections_for(info["detections"], 22, ["snyk"])
    assert mode == "none" and dets == []
    assert single_detection_of(info["detections"], ["flawfinder"])["line"] == 1    # unica do scanner
    assert single_detection_of(info["detections"], ["snyk"]) is None                # duas: ambiguo
    assert parse_info("sem nada")["detections"] == []


# --------------------------------------------------------------------------- tabelas do artigo
def test_parse_paper_table_rows():
    text = """N/L CWE Lang. Source Scanner Severity GPT-4.1 GPT-5 Opus 4.1
1/1a 772 C gpt3.5 snyk note Yes Yes No Yes No Yes
9/9 20/120 C gpt3.5 semgrep, flawfinder error, warninig Yes Yes Yes Yes No No
Table 14 qualquer outra linha
1 3"""
    rows = parse_table_text(text, "v8")
    assert [r["issue_id"] for r in rows] == ["v8:1/1a", "v8:9/9"]
    r0, r1 = rows
    assert (r0["gpt-4.1__detected"], r0["gpt-4.1__fixed"]) == (True, True)
    assert (r0["gpt-5__detected"], r0["gpt-5__fixed"]) == (False, True)       # corrigiu sem detectar
    assert (r0["opus-4.1__detected"], r0["opus-4.1__fixed"]) == (False, True)
    assert r1["paper_cwe"] == "20/120" and r1["paper_scanner_severity"] == "semgrep, flawfinder error, warninig"
    assert (r1["opus-4.1__detected"], r1["opus-4.1__fixed"]) == (False, False)

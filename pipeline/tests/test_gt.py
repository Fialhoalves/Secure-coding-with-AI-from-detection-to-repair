def test_apply_labels_review_and_overrides(ods_path):
    df = gt.read_sheet(ods_path, "v8")
    labeled, review = gt.apply_labels(df, {})
    assert labeled["is_real_label"].tolist() == ["real", "not_real", "review"]
    assert [r["issue_number"] for r in review if r["field"] == "is_real"] == [3]
    assert labeled.loc[0, "gpt-4.1__detected"] is True or labeled.loc[0, "gpt-4.1__detected"] == True  # noqa: E712
    assert labeled.loc[0, "opus-4.1__fixed"] == False  # noqa: E712

    ov = {("v8", 3, "", "is_real"): ("not_real", "texto nega problema")}
    labeled2, review2 = gt.apply_labels(df, ov)
    assert labeled2["is_real_label"].tolist() == ["real", "not_real", "not_real"]
    assert not [r for r in review2 if r["field"] == "is_real"]
    assert labeled2["is_real_source"].tolist() == ["rule", "rule", "override"]


